-- ============================================================
-- Projeto OLAP e ETL - AdventureWorks2016
-- Modelo físico PostgreSQL - Star Schema de Vendas
-- Gerado para execução no DBeaver
-- ============================================================

BEGIN;

CREATE SCHEMA IF NOT EXISTS dw;

-- ============================================================
-- DIMENSÃO TEMPO
-- ============================================================
CREATE TABLE IF NOT EXISTS dw.dim_tempo (
    sk_tempo            INTEGER PRIMARY KEY,
    data_completa       DATE NOT NULL UNIQUE,
    dia                 SMALLINT NOT NULL,
    mes                 SMALLINT NOT NULL,
    nome_mes            VARCHAR(20) NOT NULL,
    trimestre           SMALLINT NOT NULL,
    ano                 SMALLINT NOT NULL,
    dia_semana          SMALLINT NOT NULL,
    nome_dia_semana     VARCHAR(20) NOT NULL,
    semana_ano          SMALLINT NOT NULL,
    fim_de_semana       BOOLEAN NOT NULL DEFAULT FALSE,

    CONSTRAINT ck_dim_tempo_dia
        CHECK (dia BETWEEN 1 AND 31),

    CONSTRAINT ck_dim_tempo_mes
        CHECK (mes BETWEEN 1 AND 12),

    CONSTRAINT ck_dim_tempo_trimestre
        CHECK (trimestre BETWEEN 1 AND 4),

    CONSTRAINT ck_dim_tempo_ano
        CHECK (ano > 0),

    CONSTRAINT ck_dim_tempo_dia_semana
        CHECK (dia_semana BETWEEN 1 AND 7),

    CONSTRAINT ck_dim_tempo_semana_ano
        CHECK (semana_ano BETWEEN 1 AND 53)
);

-- ============================================================
-- DIMENSÃO PRODUTO
-- ============================================================
CREATE TABLE IF NOT EXISTS dw.dim_produto (
    sk_produto           INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id_oltp      INTEGER NOT NULL UNIQUE,
    nome_produto         VARCHAR(100) NOT NULL,
    numero_produto       VARCHAR(25) NOT NULL,
    cor                  VARCHAR(15),
    tamanho              VARCHAR(10),
    nome_subcategoria    VARCHAR(50) NOT NULL DEFAULT 'Não classificado',
    nome_categoria       VARCHAR(50) NOT NULL DEFAULT 'Não classificado',
    preco_lista          NUMERIC(19,4) NOT NULL,

    CONSTRAINT ck_dim_produto_preco_lista
        CHECK (preco_lista >= 0)
);

-- ============================================================
-- DIMENSÃO TERRITÓRIO
-- ============================================================
CREATE TABLE IF NOT EXISTS dw.dim_territorio (
    sk_territorio        INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    territory_id_oltp    INTEGER NOT NULL UNIQUE,
    nome_territorio      VARCHAR(50) NOT NULL,
    codigo_pais          VARCHAR(3) NOT NULL,
    grupo_territorial    VARCHAR(50) NOT NULL
);

-- ============================================================
-- MEMBROS DESCONHECIDOS / NÃO INFORMADOS
-- Mantidos para proteger futuras cargas incrementais.
-- ============================================================
INSERT INTO dw.dim_produto (
    sk_produto,
    product_id_oltp,
    nome_produto,
    numero_produto,
    cor,
    tamanho,
    nome_subcategoria,
    nome_categoria,
    preco_lista
)
VALUES (
    -1,
    -1,
    'Não informado',
    'N/A',
    NULL,
    NULL,
    'Não classificado',
    'Não classificado',
    0
)
ON CONFLICT DO NOTHING;

INSERT INTO dw.dim_territorio (
    sk_territorio,
    territory_id_oltp,
    nome_territorio,
    codigo_pais,
    grupo_territorial
)
VALUES (
    -1,
    -1,
    'Não informado',
    'N/A',
    'Não informado'
)
ON CONFLICT DO NOTHING;

-- ============================================================
-- TABELA FATO VENDA
-- Grão: 1 registro = 1 item de pedido de venda
-- ============================================================
CREATE TABLE IF NOT EXISTS dw.fato_venda (
    sk_venda                    BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- Identificadores da origem
    sales_order_id              INTEGER NOT NULL,
    sales_order_detail_id       INTEGER NOT NULL,

    -- Chaves dimensionais
    sk_tempo                    INTEGER NOT NULL,
    sk_produto                  INTEGER NOT NULL,
    sk_territorio               INTEGER NOT NULL,

    -- Medidas trazidas da origem
    quantidade                  INTEGER NOT NULL,
    preco_unitario              NUMERIC(19,4) NOT NULL,
    percentual_desconto_item    NUMERIC(9,6) NOT NULL DEFAULT 0,
    valor_receita               NUMERIC(20,6) NOT NULL,

    -- Medidas calculadas pela ETL
    valor_bruto_item            NUMERIC(20,6) NOT NULL,
    valor_desconto              NUMERIC(20,6) NOT NULL,
    custo_unitario_aplicado     NUMERIC(19,4) NOT NULL,
    origem_custo                VARCHAR(20) NOT NULL,
    custo_total                 NUMERIC(20,6) NOT NULL,
    margem_bruta                NUMERIC(20,6) NOT NULL,

    -- Integridade do grão
    CONSTRAINT uq_fato_venda_item
        UNIQUE (sales_order_id, sales_order_detail_id),

    -- Relacionamentos dimensionais
    CONSTRAINT fk_fato_venda_tempo
        FOREIGN KEY (sk_tempo)
        REFERENCES dw.dim_tempo (sk_tempo),

    CONSTRAINT fk_fato_venda_produto
        FOREIGN KEY (sk_produto)
        REFERENCES dw.dim_produto (sk_produto),

    CONSTRAINT fk_fato_venda_territorio
        FOREIGN KEY (sk_territorio)
        REFERENCES dw.dim_territorio (sk_territorio),

    -- Regras de qualidade
    CONSTRAINT ck_fato_venda_sales_order_id
        CHECK (sales_order_id > 0),

    CONSTRAINT ck_fato_venda_sales_order_detail_id
        CHECK (sales_order_detail_id > 0),

    CONSTRAINT ck_fato_venda_quantidade
        CHECK (quantidade > 0),

    CONSTRAINT ck_fato_venda_preco_unitario
        CHECK (preco_unitario >= 0),

    CONSTRAINT ck_fato_venda_percentual_desconto
        CHECK (percentual_desconto_item BETWEEN 0 AND 1),

    CONSTRAINT ck_fato_venda_valor_bruto
        CHECK (valor_bruto_item >= 0),

    CONSTRAINT ck_fato_venda_valor_desconto
        CHECK (valor_desconto >= 0 AND valor_desconto <= valor_bruto_item),

    CONSTRAINT ck_fato_venda_valor_receita
        CHECK (valor_receita >= 0),

    CONSTRAINT ck_fato_venda_custo_unitario
        CHECK (custo_unitario_aplicado >= 0),

    CONSTRAINT ck_fato_venda_custo_total
        CHECK (custo_total >= 0),

    CONSTRAINT ck_fato_venda_origem_custo
        CHECK (origem_custo IN ('HISTORICO', 'FALLBACK_ATUAL'))
);

-- ============================================================
-- ÍNDICES
-- PostgreSQL não cria automaticamente índices para as FKs
-- da tabela que referencia as dimensões.
-- ============================================================
CREATE INDEX IF NOT EXISTS idx_fato_venda_sk_tempo
    ON dw.fato_venda (sk_tempo);

CREATE INDEX IF NOT EXISTS idx_fato_venda_sk_produto
    ON dw.fato_venda (sk_produto);

CREATE INDEX IF NOT EXISTS idx_fato_venda_sk_territorio
    ON dw.fato_venda (sk_territorio);

CREATE INDEX IF NOT EXISTS idx_fato_venda_sales_order_id
    ON dw.fato_venda (sales_order_id);

-- ============================================================
-- COMENTÁRIOS DE DOCUMENTAÇÃO
-- ============================================================
COMMENT ON SCHEMA dw IS
'Data Warehouse dimensional do processo de vendas do AdventureWorks2016.';

COMMENT ON TABLE dw.fato_venda IS
'Tabela fato no grão de um item de pedido de venda.';

COMMENT ON COLUMN dw.fato_venda.sales_order_id IS
'Dimensão degenerada que identifica o pedido de venda.';

COMMENT ON COLUMN dw.fato_venda.sales_order_detail_id IS
'Identificador natural do item do pedido na origem AdventureWorks2016.';

COMMENT ON COLUMN dw.fato_venda.valor_receita IS
'Valor da linha de venda após desconto, proveniente de SalesOrderDetail.LineTotal.';

COMMENT ON COLUMN dw.fato_venda.custo_unitario_aplicado IS
'Custo histórico vigente na data da venda; na ausência de histórico, utiliza Product.StandardCost como fallback.';

COMMENT ON COLUMN dw.fato_venda.origem_custo IS
'Indica a fonte do custo: HISTORICO ou FALLBACK_ATUAL.';

COMMIT;
